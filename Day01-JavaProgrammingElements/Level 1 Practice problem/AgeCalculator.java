// Create AgeCalculator Class to compute the age of Harry
class AgeCalculator{
	public static void main(String[] args){
		
		//Storing birth year of Harry in year variable
		int year = 2000;
		
		//calculating the age
		int currentYear = 2024;
		
		int age = currentYear-year;
		
		//Display the age of Harry if the birth year is 2000
		System.out.println("Harry's age in 2024 is " + age);
	}
}
	
